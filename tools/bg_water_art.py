#!/usr/bin/env python3
"""Dynamic Water (sprite 802) placed in the tutorial's backgrounds. It draws a
translucent wave strip with ActionScript at runtime, which FFDec cannot
render; this lists every placement with its parameters (the onClipEvent(load)
values over 802's defaults) for the port to simulate and draw
(assets/generated/bg_water_places.h, source/game/bg_water.c)."""
import re
from pathlib import Path

WATER = 802
DEFAULTS = {'WaterDeepness': 400, 'WaterLength': 500, 'polygons': 50, 'randomwave': 1, 'waterstength': 0.3,
            'redcolor': 40, 'greencolor': 128, 'bluecolor': 215, 'alpha': 50}
KINDS = {'Background': 'ART_LAYER_BG', 'MidBackground': 'ART_LAYER_MID', 'CloseBackground': 'ART_LAYER_CLOSE'}


def params(scripts, sprite, depth):
    vals = dict(DEFAULTS)
    for d in scripts.glob(f'DefineSprite_{sprite}*/frame_1/PlaceObject*_{WATER}_{depth}'):
        for f in d.glob('*.as'):
            for k, v in re.findall(r'(\w+)\s*=\s*([-\d.]+)\s*;', f.read_text(errors='ignore')):
                if k in vals:
                    vals[k] = float(v)
    return vals


def header(areas, tables, table, sprites, scripts):
    rows = []
    for a in areas:
        for layer, kind in KINDS.items():
            link = tables.get(a + layer)
            if not link or link not in table:
                continue
            ident = table[link]
            for depth, e in sorted(sprites[ident]['stage'][0].items()):
                if e.get('id') != WATER:
                    continue
                m, p = e['matrix'], params(scripts, ident, depth)
                if abs(m['sx'] - m['sy']) > 1e-3 or m['r0'] or m['r1']:
                    raise ValueError('Dynamic Water placed rotated or stretched')
                rows.append('    {"%s", %s, %.2ff, %.2ff, %.4ff, %.1ff, %.1ff, %du, %.3ff, %.3ff, {%d, %d, %d, %d}},' % (
                    a, kind, m['tx'] / 20, m['ty'] / 20, m['sx'], p['WaterLength'], p['WaterDeepness'],
                    int(p['polygons']), p['waterstength'], p['randomwave'], int(p['redcolor']), int(p['greencolor']),
                    int(p['bluecolor']), round(p['alpha'] * 255 / 100)))
    return '\n'.join([
        '/* Generated by tools/bg_water_art.py (via export_course_art.py); do not edit.',
        '   Dynamic Water (802) in the backgrounds: background px (the layer\'s registration),',
        '   its _xscale, WaterLength, WaterDeepness, polygons, waterstength, randomwave, colour. */',
        '#ifndef SM63_BG_WATER_PLACES_H', '#define SM63_BG_WATER_H', '#include "course_art.h"',
        'typedef struct { const char *area; CourseArtKind kind; float x, y, scale, length, deep; unsigned points;',
        '                 float stiffness, randomwave; unsigned char rgba[4]; } BgWaterPlace;',
        'static const BgWaterPlace bg_waters[] = {'] + rows + [
        '};', '#define BG_WATERS (sizeof(bg_waters) / sizeof(bg_waters[0]))', '#endif', ''])
