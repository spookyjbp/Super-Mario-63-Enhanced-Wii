#!/usr/bin/env python3
"""Port-made water textures (the 2010 tutorial's lake is drawn by the port).

Two GX RGB5A3 textures, both seamlessly tileable horizontally (every wave and
light pattern has a whole number of periods across the tile) so a water volume
of any width is one repeating quad with no seams:

* body (64 x 64): translucent blue with soft caustic light bands, also tileable
  vertically; scrolled slowly at runtime;
* surface (64 x 16, 8 animation frames stacked into 64 x 128): a bright wave
  crest with a white highlight, a light band below it fading into the body
  colour, transparent above the crest.

Colours follow the tutorial's palette (the sky and the waterfall clips:
saturated blues with white highlights), alpha about 60 % so the art behind
stays readable.

    python make_water_texture.py <out_header>
"""
import argparse
import math
from pathlib import Path
import numpy as np
from PIL import Image
from build_player_art import rgb5a3_tiles

BODY = (64, 64)
SURFACE = (64, 16)
FRAMES = 8
DEEP = np.array([30, 104, 220], float)
LIGHT = np.array([110, 196, 255], float)
FOAM = np.array([236, 250, 255], float)


def body():
    w, h = BODY
    y, x = np.mgrid[0:h, 0:w] / np.array([h, w])[:, None, None]
    # two crossing sets of soft bands (whole periods: tileable both ways)
    a = np.sin(2 * math.pi * (2 * x + 1 * y)) + np.sin(2 * math.pi * (1 * x - 2 * y) + 1.3)
    b = np.sin(2 * math.pi * (3 * x + 2 * y) + 0.7) * 0.5
    t = np.clip((a + b) / 2.5, -1, 1)
    light = np.clip((t - 0.35) / 0.65, 0, 1) ** 1.6  # thin bright ridges only
    rgb = DEEP + (LIGHT - DEEP) * (0.25 + 0.75 * light[..., None])
    alpha = 150 + 30 * light
    return np.dstack([rgb, alpha]).round().clip(0, 255).astype(np.uint8)


def surface(frame):
    w, h = SURFACE
    out = np.zeros((h, w, 4), float)
    phase = 2 * math.pi * frame / FRAMES
    for xi in range(w):
        u = xi / w
        crest = 5.0 + 1.6 * math.sin(2 * math.pi * 2 * u + phase) + 0.7 * math.sin(2 * math.pi * 5 * u - 2 * phase)
        for yi in range(h):
            d = yi + 0.5 - crest  # px below the crest line
            if d < -1:
                continue
            cover = min(1.0, d + 1.0)  # antialiased top edge
            if d < 1.6:  # white highlight on the crest
                rgb, a = FOAM, 235
            else:  # light band fading into the body colour
                k = min(1.0, (d - 1.6) / (h - 7))
                rgb, a = LIGHT + (DEEP + (LIGHT - DEEP) * 0.25 - LIGHT) * k, 200 - 45 * k
            out[yi, xi, :3] = rgb
            out[yi, xi, 3] = a * cover
    # transparent texels take the colour below them (bilinear filtering)
    for xi in range(w):
        first = next(yi for yi in range(h) if out[yi, xi, 3] > 0)
        out[:first, xi, :3] = out[first, xi, :3]
    return out.round().clip(0, 255).astype(np.uint8)


def header(path):
    b = body()
    s = np.concatenate([surface(f) for f in range(FRAMES)], axis=0)
    lines = ['/* Generated by tools/make_water_texture.py; do not edit. Port-made water',
             '   textures (GX RGB5A3, tileable horizontally; the body also vertically). */',
             '#ifndef SM63_WATER_TEX_H', '#define SM63_WATER_TEX_H',
             f'#define WATER_BODY_W {BODY[0]}', f'#define WATER_BODY_H {BODY[1]}',
             f'#define WATER_SURFACE_W {SURFACE[0]}', f'#define WATER_SURFACE_H {SURFACE[1]}',
             f'#define WATER_SURFACE_FRAMES {FRAMES}']
    for name, arr in (('water_body_tex', b), ('water_surface_tex', s)):
        data = rgb5a3_tiles(Image.fromarray(arr))
        lines.append(f'static const unsigned char {name}[{len(data)}] __attribute__((aligned(32))) = {{')
        for i in range(0, len(data), 24):
            lines.append('    ' + ', '.join(str(v) for v in data[i:i + 24]) + ',')
        lines.append('};')
    lines += ['#endif', '']
    Path(path).write_text('\n'.join(lines))
    return b, s


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('out', type=Path)
    p.add_argument('--preview', type=Path)
    a = p.parse_args()
    b, s = header(a.out)
    if a.preview:
        Image.fromarray(np.concatenate([np.tile(b, (1, 3, 1)), np.tile(s[:64], (1, 3, 1))], axis=0)).save(a.preview)
    print('Wrote', a.out)
