#!/usr/bin/env python3
"""The 0 HP faint's screens, for the art pack (export_course_art.py):

* "StarOut~" (Blackout 7433) and "StarIn~" (StarIn 7434): the star wipe to
  black and back, attached at the stage centre. Rendered at half the screen
  scale (they are flat black shapes) and drawn twice as large.
* "LifeLost~" (LifeLost 7473): the lives screen. Its text field 'lives' shows
  _root.CharLives + 1 until frame 28, then CharLives; in the tutorial (no stars
  yet) LifeLost() takes no life, so it always counts 5 down to 4. Each frame
  is stored as its flat background colour plus the pixels that differ from it.

Returns layers [(name, frames [(x, y, image)], ox, oy, W, H, scale)] and the
faint_layout.h text (background colours, timings).
"""
import numpy as np
from PIL import Image
import ui_art

BLACKOUT, STARIN, LIFELOST = 7433, 7434, 7473
LIVES_FIELD = b'lives\x000\x00'


def _frames(jar, work, swf_path, ident, count, zoom, tag):
    old = ui_art.ZOOM
    ui_art.ZOOM = zoom
    try:
        d = ui_art.ffdec(jar, work, swf_path, ident, range(1, count + 1), work / tag)
        sv = ui_art.ffdec(jar, work, swf_path, ident, [1], work / (tag + '-svg'), svg=True)
        with Image.open(d / '1.png') as p1:
            ox, oy = ui_art.png_origin(sv / '1.svg', p1.size, zoom)
    finally:
        ui_art.ZOOM = old
    return [Image.open(d / f'{f}.png').convert('RGBA') for f in range(1, count + 1)], ox, oy


def _crop4(im, bb):
    x0, y0 = bb[0] // 4 * 4, bb[1] // 4 * 4
    x1, y1 = min(-(-bb[2] // 4) * 4, -(-im.width // 4) * 4), min(-(-bb[3] // 4) * 4, -(-im.height // 4) * 4)
    canvas = Image.new('RGBA', (-(-im.width // 4) * 4, -(-im.height // 4) * 4))
    canvas.paste(im, (0, 0))
    return x0, y0, canvas.crop((x0, y0, x1, y1))


def build(work, jar, swf_bytes, sprites):
    work.mkdir(parents=True, exist_ok=True)
    plain = work / 'faint.swf'
    plain.write_bytes(swf_bytes)
    layers, header = [], ['/* Generated by tools/faint_art.py (via export_course_art.py); do not edit. */',
                          '#ifndef SM63_FAINT_LAYOUT_H', '#define SM63_FAINT_LAYOUT_H']
    for name, ident in (('StarOut~', BLACKOUT), ('StarIn~', STARIN)):
        n = sprites[ident]['frames']
        ims, ox, oy = _frames(jar, work, plain, ident, n, 0.8, name.strip('~').lower())
        frames = []
        for im in ims:
            bb = im.getchannel('A').getbbox()
            frames.append((0, 0, Image.new('RGBA', (4, 4))) if bb is None else _crop4(im, bb))
        W, H = -(-ims[0].width // 4) * 4, -(-ims[0].height // 4) * 4
        layers.append((name, frames, 225 + ox, 150 + oy, W, H, 0.8))
        header.append(f'#define FAINT_{name.strip("~").upper()}_FRAMES {n}')
    # the lives screen, the field showing 5 and then 4
    n = sprites[LIFELOST]['frames']
    renders = {}
    for digit in (b'5', b'4'):
        if swf_bytes.count(LIVES_FIELD) != 1:
            raise ValueError('LifeLost lives field not found once')
        path = work / f'lifelost-{digit.decode()}.swf'
        path.write_bytes(swf_bytes.replace(LIVES_FIELD, b'lives\x00' + digit + b'\x00'))
        renders[digit], ox, oy = _frames(jar, work, path, LIFELOST, n, 1.6, f'lifelost-{digit.decode()}')
    frames, colours = [], []
    for f in range(n):
        im = renders[b'5' if f < 27 else b'4'][f]   # frame 28: lives = _root.CharLives
        a = np.asarray(im).astype(int)
        # the screen's flat colour (black, or the red flash): left of the middle,
        # inside the black rectangle (the canvas margin around it is empty)
        bg = a[a.shape[0] // 2, a.shape[1] // 8]
        colours.append(tuple(int(v) for v in bg))
        diff = (a[..., 3] > 0) & (np.abs(a - bg).sum(-1) > 12)
        diff[:6], diff[-6:], diff[:, :6], diff[:, -6:] = False, False, False, False   # the rectangle's anti-aliased edge
        if not diff.any():
            frames.append((0, 0, Image.new('RGBA', (4, 4))))
            continue
        ys, xs = np.nonzero(diff)
        frames.append(_crop4(im, (xs.min(), ys.min(), xs.max() + 1, ys.max() + 1)))
    W, H = -(-renders[b'5'][0].width // 4) * 4, -(-renders[b'5'][0].height // 4) * 4
    layers.append(('LifeLost~', frames, 225 + ox, 150 + oy, W, H, 1.6))
    header.append(f'#define FAINT_LIFELOST_FRAMES {n}')
    header.append('/* LifeLost 7473: the flat colour under each frame (RGBA). */')
    header.append('static const unsigned char faint_lifelost_bg[FAINT_LIFELOST_FRAMES][4] = {')
    header += ['    {%d, %d, %d, %d},' % c for c in colours]
    header += ['};', '#endif', '']
    return layers, '\n'.join(header)
