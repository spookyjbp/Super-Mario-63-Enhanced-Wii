#!/usr/bin/env python3
"""Rebuild the checked-in GX atlas from unchanged upstream PNGs (requires Pillow)."""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SIZE = 256
CELL = 40


def rgba8_tiles(image):
    """GX RGBA8 stores each 4x4 block as 16 AR pairs followed by 16 GB pairs."""
    out = bytearray()
    for by in range(0, image.height, 4):
        for bx in range(0, image.width, 4):
            block = [image.getpixel((bx + x, by + y)) for y in range(4) for x in range(4)]
            out.extend(value for r, g, b, a in block for value in (a, r))
            out.extend(value for r, g, b, a in block for value in (g, b))
    return bytes(out)


def build():
    manifest = json.loads((ROOT / 'assets/mario/manifest.json').read_text())
    atlas = Image.new('RGBA', (SIZE, SIZE))
    frames = []
    for i, frame in enumerate(manifest['frames']):
        source = ROOT / 'assets/mario/source' / frame['file']
        if hashlib.sha256(source.read_bytes()).hexdigest() != frame['sha256']:
            raise ValueError(f'Source checksum mismatch: {source}')
        image = Image.open(source).convert('RGBA')
        x, y = (i % 6) * CELL + 2, (i // 6) * CELL + 2
        if image.width > CELL - 4 or image.height > CELL - 4 or y + CELL > SIZE:
            raise ValueError('Sprite does not fit atlas cell')
        atlas.paste(image, (x, y))  # No resampling or alpha compositing.
        facing = frame['native_facing'].upper()
        if facing not in ('RIGHT', 'LEFT', 'FRONT', 'BACK_LEFT', 'BACK'):
            raise ValueError(f'Unknown native facing: {facing}')
        mirror = int(frame['mirror_for_right'])
        frames.append(f'    {{{x}, {y}, {image.width}, {image.height}, MARIO_FACE_{facing}, {mirror}}},')
    header = '\n'.join([
        '/* Generated by tools/build_mario_atlas.py; do not edit. */',
        '#ifndef SM63_MARIO_ATLAS_H', '#define SM63_MARIO_ATLAS_H',
        '#define MARIO_ATLAS_SIZE 256',
        'enum { MARIO_FACE_RIGHT, MARIO_FACE_LEFT, MARIO_FACE_FRONT, MARIO_FACE_BACK_LEFT, MARIO_FACE_BACK };',
        'typedef struct { unsigned short x, y, width, height; unsigned char native_facing, mirror_for_right; } MarioFrame;',
        'static const MarioFrame mario_frames[] = {', *frames, '};',
        '#endif', ''
    ])
    return atlas, rgba8_tiles(atlas), header


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='Verify checked-in generated outputs')
    args = parser.parse_args()
    image, binary, header = build()
    output = ROOT / 'assets/generated'
    if args.check:
        assert (output / 'mario_rgba8.bin').read_bytes() == binary, 'GX texture is stale'
        assert (output / 'mario_atlas.h').read_text() == header, 'Atlas header is stale'
        with Image.open(output / 'mario_atlas.png') as preview:
            assert preview.convert('RGBA').tobytes() == image.tobytes(), 'Preview is stale'
        print('Original PNG checksums, atlas pixels, GX tiles and frame bounds verified')
    else:
        output.mkdir(parents=True, exist_ok=True)
        image.save(output / 'mario_atlas.png')
        (output / 'mario_rgba8.bin').write_bytes(binary)
        (output / 'mario_atlas.h').write_text(header)
