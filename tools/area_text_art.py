#!/usr/bin/env python3
"""The area name as the original shows it (AreaTextClip 7515, for the art pack;
export_course_art.py).

_root.AreaTextClipF(txt, frame) attaches AreaTextClip in Stats at (225, 75)
with the text and gotoAndStop(frame): the frame only picks the colour matrix
filter on its bar ('bg', 7509: a bar with dark edges and faded ends). The
tutorial uses frame 45 (a dark teal bar) and the text
"Mushroom Kingdom\\r<i>(Tutorial)</i>" (8-E1-1BackGFX frame 3). The text clip
(7514, 95 frames) waits 9 frames on frame 1 (count > 8), then frames 2-11 blur
the text in (7510) while the bar fades in (_alpha += 10), 12-84 hold (7511),
85-94 blur it out (7512) with the bar fading, and 95 removes the clip. Its
text fields (Arial 20, white, a dark outline) show _parent.txt.

Each distinct frame (bar at its alpha + text) becomes a tile of "AreaText~";
area_text_layout.h maps the 95 clip frames to tiles and gives the timings.
"""
import struct
import numpy as np
from PIL import Image
import swf_states as S
import swf_bitmap_fix as F
import ui_art

CLIP, TEXT_CLIP, BAR, FIELDS = 7515, 7514, 7509, (7510, 7511, 7512, 7513)
FRAME = 45
ZOOM = 1.6
LINE = ('<p align="center"><font face="Arial" size="20" color="#ffffff" letterSpacing="0.000000" kerning="0">'
        '{}</font></p>')
TUTORIAL = LINE.format('Mushroom Kingdom') + LINE.format('<i>(Tutorial)</i>')
# the area names shown, in area_text_tile's order: (layer name, text, AreaTextClipF frame)
NAMES = [
    ('AreaText~', TUTORIAL, 45),                     # 8-E1-1BackGFX frame 3
    # CastleBackGFX frame 1: AreaTextClipF("Castle Grounds:\r<i>Outside the Castle</i>", 35)
    ('AreaText2~', LINE.format('Castle Grounds:') + LINE.format('<i>Outside the Castle</i>'), 35),
]


def with_text(swf, html):
    """The SWF with the text fields' initial text replaced (FFDec shows it)."""
    raw, start = S.body(swf)
    out, n = bytearray(raw[:start]), 0
    for code, pos, length in S.tags(raw, start, len(raw)):
        data = raw[pos:pos + length]
        if code == 37 and struct.unpack_from('<H', data)[0] in FIELDS:
            i = data.index(b'_parent.txt\x00') + len(b'_parent.txt\x00')
            data = data[:i] + html.encode('latin1') + b'\x00'
            n += 1
        out += F._tag(code, data)
    if n != len(FIELDS):
        raise ValueError(f'AreaTextClip fields: found {n}')
    return b'FWS' + swf[3:4] + struct.pack('<I', len(out) + 8) + bytes(out)


def bar_alpha(f):
    """bg._alpha on 7514's frame f (1-based)."""
    if f <= 1:
        return 0
    if f <= 10:
        return 10 * (f - 1)
    if f <= 85:
        return 100
    return max(0, 100 - 10 * (f - 85))


def _render(jar, work, swf_path, ident, frames, tag):
    old = ui_art.ZOOM
    ui_art.ZOOM = ZOOM
    try:
        d = ui_art.ffdec(jar, work, swf_path, ident, frames, work / tag)
        sv = ui_art.ffdec(jar, work, swf_path, ident, [frames[0]], work / (tag + '-svg'), svg=True)
        with Image.open(d / f'{frames[0]}.png') as p:
            ox, oy = ui_art.png_origin(sv / f'{frames[0]}.svg', p.size, ZOOM)
    finally:
        ui_art.ZOOM = old
    return {f: Image.open(d / f'{f}.png').convert('RGBA') for f in frames}, ox, oy


def build(work, jar, swf):
    layers, tables = [], []
    for k, (name, html, frame) in enumerate(NAMES):
        layer, table = build_one(work / str(k), jar, swf, name, html, frame)
        layers.append(layer); tables.append(table)
    header = ['/* Generated by tools/area_text_art.py (via export_course_art.py); do not edit. */',
              '#ifndef SM63_AREA_TEXT_LAYOUT_H', '#define SM63_AREA_TEXT_LAYOUT_H',
              '/* AreaTextClip: 9 frames waiting on frame 1, then 7514 frames 2-94; 95 removes it. */',
              '#define AREA_TEXT_WAIT 9', '#define AREA_TEXT_FRAMES 94',
              f'#define AREA_TEXT_NAMES {len(NAMES)}',
              '/* the art layer of each area name (area_text index): ' + ', '.join(n for n, _, _ in NAMES) + ' */',
              'static const char *const area_text_layer[AREA_TEXT_NAMES] = {' +
              ', '.join(f'"{n}"' for n, _, _ in NAMES) + '};',
              '/* the layer\'s tile for each of 7514 frames 1..94 */',
              'static const unsigned char area_text_tile[AREA_TEXT_NAMES][AREA_TEXT_FRAMES] = {']
    for t in tables:
        header.append('    {' + ', '.join(map(str, t)) + '},')
    header += ['};', '#endif', '']
    return layers, '\n'.join(header)


def build_one(work, jar, swf, name, html, frame):
    work.mkdir(parents=True, exist_ok=True)
    path = work / 'areatext.swf'
    path.write_bytes(with_text(swf, html))
    bar_path = work / 'areabar.swf'
    bar_path.write_bytes(ui_art.hide(swf, {CLIP: {TEXT_CLIP}}))
    texts, tx, ty = _render(jar, work, path, TEXT_CLIP, list(range(2, 95)), 'areatext')
    bars, bx, by = _render(jar, work, bar_path, CLIP, [frame], 'areabar')
    bar = bars[frame]
    # one canvas in clip coordinates around both
    x0, y0 = min(tx, bx), min(ty, by)
    x1 = max(tx + texts[2].width / ZOOM, bx + bar.width / ZOOM)
    y1 = max(ty + texts[2].height / ZOOM, by + bar.height / ZOOM)
    W, H = -(-round((x1 - x0) * ZOOM) // 4) * 4, -(-round((y1 - y0) * ZOOM) // 4) * 4
    tiles, keys, frame_tile = [], {}, []
    for f in range(1, 95):
        c = Image.new('RGBA', (W, H))
        a = bar_alpha(f)
        if a:
            b = bar.copy()
            b.putalpha(b.getchannel('A').point(lambda v: v * a // 100))
            c.alpha_composite(b, (round((bx - x0) * ZOOM), round((by - y0) * ZOOM)))
        if f >= 2:
            c.alpha_composite(texts[f], (round((tx - x0) * ZOOM), round((ty - y0) * ZOOM)))
        key = c.tobytes()
        if key not in keys:
            bb = c.getchannel('A').getbbox()
            if bb is None:
                tile = (0, 0, Image.new('RGBA', (4, 4)))
            else:
                l, t = bb[0] // 4 * 4, bb[1] // 4 * 4
                r, btm = min(W, -(-bb[2] // 4) * 4), min(H, -(-bb[3] // 4) * 4)
                tile = (l, t, c.crop((l, t, r, btm)))
            keys[key] = len(tiles)
            tiles.append(tile)
        frame_tile.append(keys[key])
    # stage placement: Stats at (225, 75) (the stage centre is 225, 150 in faint_art's terms)
    return (name, tiles, 225 + x0, 75 + y0, W, H, ZOOM), frame_tile

