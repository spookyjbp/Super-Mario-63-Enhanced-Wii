#!/usr/bin/env python3
"""Validate immutable level schema v1 and emit deterministic C data (stdlib only)."""
import argparse
import json
import math
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
TILES={'.':0,'#':1,'=':2,'/':3,'\\':4,'~':5,'I':6,'P':7,'!':8}

def compile_level(data):
    if data.get('schema_version') != 1: raise ValueError('Unsupported level schema')
    if not isinstance(data.get('name'),str) or not data['name']: raise ValueError('Invalid level name')
    size=data['tile_size']; rows=data['tiles']; spawn=data['spawn']
    if type(size) is not int or not 16<=size<=128: raise ValueError('Invalid tile size')
    if not rows or not rows[0] or len(rows)>256 or len(rows[0])>256: raise ValueError('Invalid dimensions')
    width=len(rows[0])
    if any(len(row)!=width or any(c not in TILES for c in row) for row in rows):
        raise ValueError('Nonrectangular map or unknown tile')
    if len(spawn)!=2 or any(type(v) is not int for v in spawn): raise ValueError('Invalid spawn')
    x,y=spawn
    if not 0<=x<=width*size-28 or not 0<=y<=len(rows)*size-44: raise ValueError('Spawn outside world')
    for py in range(y//size,(y+43)//size+1):
        for px in range(x//size,(x+27)//size+1):
            if rows[py][px] not in '.~': raise ValueError('Spawn overlaps terrain')
    backgrounds=data.get('backgrounds',[])
    if not 1<=len(backgrounds)<=4: raise ValueError('Need 1..4 parallax layers')
    lines=['/* Generated by tools/build_level.py; do not edit. */',
           '#ifndef SM63_MOVEMENT_LEVEL_H','#define SM63_MOVEMENT_LEVEL_H',
           '#include "level.h"','static const uint8_t movement_tiles[] = {']
    lines += ['    '+','.join(str(TILES[c]) for c in row)+',' for row in rows]
    lines+=['};','static const BackgroundLayer movement_backgrounds[] = {']
    for b in backgrounds:
        values=[b[k] for k in ('parallax','spacing','y','width','height')]+b['color']
        if any(type(b[k]) not in (int,float) or not math.isfinite(b[k]) for k in ('parallax','spacing','y','width','height')):
            raise ValueError('Background values must be finite numbers')
        if len(b['color'])!=3 or not 0<=b['parallax']<=1 or any(type(c) is not int or not 0<=c<=255 for c in b['color']):
            raise ValueError('Invalid background')
        if any(type(b[k]) not in (int,float) or not 1<=b[k]<=8192 for k in ('spacing','width','height')):
            raise ValueError('Invalid background dimensions')
        lines.append('    {'+','.join(str(v) for v in values)+'},')
    lines+=['};',f'static const Level movement_level = {{1,{width},{len(rows)},{size},movement_tiles,movement_backgrounds,{len(backgrounds)}}};',
            f'#define MOVEMENT_WORLD_WIDTH {width*size}',f'#define MOVEMENT_WORLD_HEIGHT {len(rows)*size}',
            f'#define MOVEMENT_SPAWN_X {x}',f'#define MOVEMENT_SPAWN_Y {y}','#endif','']
    return '\n'.join(lines)
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    output=ROOT/'assets/generated/movement_level.h'
    result=compile_level(json.loads((ROOT/'levels/movement.json').read_text()))
    if args.check:
        assert output.read_text()==result,'Level header is stale'
        print('Level schema, tile data, spawn and generated C verified')
    else: output.write_text(result)
